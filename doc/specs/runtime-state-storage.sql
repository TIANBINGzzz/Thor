-- 设计提案，未实施；适用于已核对的 MySQL 8.0.45 系列。不得直接对共享环境执行。
-- 这是字段设计参考，不是 Flyway 迁移；现有 conversation/message/attachment 表保持不变。
-- 表关系不代替身份、角色、文件 ACL 校验；业务 ID 的类型/排序规则与现有表一致。
-- Runtime opaque ID 保留现协议 256 字符容量，ASCII 区分大小写；业务映射 ID 仍为 36。
-- 所有时间以 UTC 写入；状态转换、幂等比较、字段白名单与凭据排除由可信服务端强校验。

CREATE TABLE t_ai_center_runtime_session (
    conversation_id VARCHAR(36) COLLATE utf8mb4_0900_ai_ci NOT NULL COMMENT '既有业务会话ID，不新造会话ID',
    tenant_id_ VARCHAR(64) NOT NULL COMMENT '已校验租户，禁止缺失时填默认值',
    user_id VARCHAR(64) NOT NULL COMMENT 'Java已认定的当前主体，保留历史标识语义',
    queue_state VARCHAR(16) NOT NULL DEFAULT 'active' COMMENT 'active/paused/closed；不表示当前Run暂停',
    active_run_id VARCHAR(256) CHARACTER SET ascii COLLATE ascii_bin NULL COMMENT '当前独占执行或待恢复Run',
    last_queue_seq BIGINT UNSIGNED NOT NULL DEFAULT 0 COMMENT 'Java在会话锁下分配；只增不减',
    last_command_seq BIGINT UNSIGNED NOT NULL DEFAULT 0 COMMENT 'Java在会话锁下分配命令顺序',
    last_event_seq BIGINT UNSIGNED NOT NULL DEFAULT 0 COMMENT 'Java/Python在会话锁和状态事务内分配',
    projected_event_seq BIGINT UNSIGNED NOT NULL DEFAULT 0 COMMENT 'Java与业务消息投影同事务推进',
    revision BIGINT UNSIGNED NOT NULL DEFAULT 0 COMMENT '可见队列状态版本，不是事件消费游标',
    runtime_session_ref VARCHAR(256) CHARACTER SET ascii COLLATE ascii_bin NULL COMMENT 'SDK会话引用，不等于runId',
    workspace_id CHAR(32) CHARACTER SET ascii COLLATE ascii_bin NULL COMMENT '受控持久数据区标识，非宿主机绝对路径',
    lease_owner VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin NULL COMMENT 'Worker进程实例标识',
    lease_epoch BIGINT UNSIGNED NOT NULL DEFAULT 0 COMMENT '每次接管递增，拒绝旧Worker回写',
    lease_expires_at DATETIME(3) NULL COMMENT '使用数据库UTC时间判断；到期不代表工具已停止',
    created_at DATETIME(3) NOT NULL,
    updated_at DATETIME(3) NOT NULL,
    PRIMARY KEY (conversation_id),
    UNIQUE KEY uk_rts_scope (conversation_id, tenant_id_, user_id),
    UNIQUE KEY uk_rts_workspace (workspace_id),
    KEY idx_rts_dispatch (queue_state, lease_expires_at),
    KEY idx_rts_projection (updated_at),
    CONSTRAINT fk_rts_conversation FOREIGN KEY (conversation_id) REFERENCES t_ai_center_conversation (id),
    CONSTRAINT ck_rts_state CHECK (queue_state IN ('active', 'paused', 'closed')),
    CONSTRAINT ck_rts_cursor CHECK (projected_event_seq <= last_event_seq),
    CONSTRAINT ck_rts_lease CHECK ((lease_owner IS NULL AND lease_expires_at IS NULL) OR (lease_owner IS NOT NULL AND lease_expires_at IS NOT NULL))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_bin COMMENT='会话级调度与Java投影游标';

CREATE TABLE t_ai_center_runtime_run (
    run_id VARCHAR(256) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT '既有Run协议ID',
    conversation_id VARCHAR(36) COLLATE utf8mb4_0900_ai_ci NOT NULL,
    tenant_id_ VARCHAR(64) NOT NULL,
    user_id VARCHAR(64) NOT NULL,
    user_message_id VARCHAR(36) COLLATE utf8mb4_0900_ai_ci NOT NULL COMMENT '输入消息，可被多次重新回答复用',
    assistant_message_id VARCHAR(36) COLLATE utf8mb4_0900_ai_ci NOT NULL COMMENT '本次回答；Java现有wire messageId',
    request_key VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT '浏览器一次提交的幂等键，重试沿用；不是新生命周期ID',
    capability_ref VARCHAR(256) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    queue_seq BIGINT UNSIGNED NOT NULL COMMENT '会话内入队顺序，取消后不回收',
    status VARCHAR(32) NOT NULL DEFAULT 'queued',
    phase VARCHAR(64) NULL COMMENT '公开执行阶段，不替代恢复检查点',
    wait_reason VARCHAR(64) NULL COMMENT 'authorization_required/config_unavailable/workspace_unavailable等',
    revision BIGINT UNSIGNED NOT NULL DEFAULT 1 COMMENT '输入或生命周期改变时递增；编辑保存使用CAS',
    input_revision BIGINT UNSIGNED NOT NULL DEFAULT 1 COMMENT '仅已接受的输入变化时递增，授权绑定此版本',
    request_json JSON NOT NULL COMMENT '带schemaVersion的白名单输入；禁止凭据、签名URL及环境变量',
    request_hash CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NULL COMMENT 'Python校验后生成；编辑后清空并重算',
    execution_snapshot JSON NULL COMMENT '可信解析后的资产引用/摘要/部署版本，无秘密',
    runtime_session_ref VARCHAR(256) CHARACTER SET ascii COLLATE ascii_bin NULL COMMENT '本Run实际使用的SDK历史引用',
    checkpoint_stage VARCHAR(32) NOT NULL DEFAULT 'none',
    checkpoint_json JSON NULL COMMENT '已完成文件清单/校验和/持久result引用；不是Python堆栈',
    sdk_started_at DATETIME(3) NULL COMMENT '必须在首次发送SDK之前写入，崩溃后保守视为可能已发送',
    sdk_result_sequence BIGINT UNSIGNED NULL COMMENT '已落盘result所在的Run事件sequence',
    retry_of_run_id VARCHAR(256) CHARACTER SET ascii COLLATE ascii_bin NULL COMMENT '用户重新回答时新Run引用旧Run',
    redirected_to_run_id VARCHAR(256) CHARACTER SET ascii COLLATE ascii_bin NULL COMMENT '队列转引导的目标Run',
    edit_owner VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin NULL COMMENT '浏览器编辑实例标识，不是登录Token',
    edit_expires_at DATETIME(3) NULL COMMENT '编辑锁失联后自动失效，队首不可跳过',
    last_sequence BIGINT UNSIGNED NOT NULL DEFAULT 0 COMMENT '现有agent-events/v1的Run序号',
    error_code VARCHAR(64) NULL COMMENT '受控错误码，不存原始异常/凭据',
    created_at DATETIME(3) NOT NULL,
    started_at DATETIME(3) NULL COMMENT '实际获执行位，不能在入队时标started',
    ended_at DATETIME(3) NULL,
    updated_at DATETIME(3) NOT NULL,
    PRIMARY KEY (run_id),
    UNIQUE KEY uk_rtr_session_run (conversation_id, run_id),
    UNIQUE KEY uk_rtr_assistant (assistant_message_id),
    UNIQUE KEY uk_rtr_request (conversation_id, request_key),
    UNIQUE KEY uk_rtr_order (conversation_id, queue_seq),
    KEY idx_rtr_queue (conversation_id, status, queue_seq),
    KEY idx_rtr_user_message (user_message_id),
    CONSTRAINT fk_rtr_scope FOREIGN KEY (conversation_id, tenant_id_, user_id) REFERENCES t_ai_center_runtime_session (conversation_id, tenant_id_, user_id),
    CONSTRAINT fk_rtr_user_message FOREIGN KEY (user_message_id) REFERENCES t_ai_center_message (id),
    CONSTRAINT fk_rtr_assistant FOREIGN KEY (assistant_message_id) REFERENCES t_ai_center_message (id),
    CONSTRAINT fk_rtr_retry FOREIGN KEY (conversation_id, retry_of_run_id) REFERENCES t_ai_center_runtime_run (conversation_id, run_id),
    CONSTRAINT fk_rtr_redirect FOREIGN KEY (conversation_id, redirected_to_run_id) REFERENCES t_ai_center_runtime_run (conversation_id, run_id),
    CONSTRAINT ck_rtr_status CHECK (status IN ('queued', 'waiting', 'preparing', 'running', 'finalizing', 'completed', 'cancelled', 'failed', 'interrupted', 'redirecting', 'redirected', 'steering_unknown')),
    CONSTRAINT ck_rtr_checkpoint CHECK (checkpoint_stage IN ('none', 'input_prepared', 'sdk_result_saved')),
    CONSTRAINT ck_rtr_result CHECK (checkpoint_stage <> 'sdk_result_saved' OR (sdk_result_sequence IS NOT NULL AND sdk_result_sequence > 0 AND sdk_result_sequence <= last_sequence)),
    CONSTRAINT ck_rtr_redirect CHECK (status NOT IN ('redirecting', 'redirected', 'steering_unknown') OR (redirected_to_run_id IS NOT NULL AND redirected_to_run_id <> run_id)),
    CONSTRAINT ck_rtr_retry CHECK (retry_of_run_id IS NULL OR retry_of_run_id <> run_id),
    CONSTRAINT ck_rtr_order CHECK (queue_seq > 0 AND input_revision > 0 AND revision >= input_revision),
    CONSTRAINT ck_rtr_edit CHECK ((edit_owner IS NULL AND edit_expires_at IS NULL) OR (edit_owner IS NOT NULL AND edit_expires_at IS NOT NULL))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_bin COMMENT='运行与队列的唯一权威记录';

ALTER TABLE t_ai_center_runtime_session
    ADD CONSTRAINT fk_rts_active_run FOREIGN KEY (conversation_id, active_run_id) REFERENCES t_ai_center_runtime_run (conversation_id, run_id);

CREATE TABLE t_ai_center_runtime_command (
    command_id VARCHAR(256) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT '一次控制意图的幂等键，重试复用',
    conversation_id VARCHAR(36) COLLATE utf8mb4_0900_ai_ci NOT NULL,
    command_seq BIGINT UNSIGNED NOT NULL COMMENT '会话内控制意图顺序',
    command_type VARCHAR(32) NOT NULL,
    target_run_id VARCHAR(256) CHARACTER SET ascii COLLATE ascii_bin NULL COMMENT '命令作用的Run；队列控制为空',
    source_run_id VARCHAR(256) CHARACTER SET ascii COLLATE ascii_bin NULL COMMENT '仅排队转引导填写源Run',
    steering_message_id VARCHAR(36) COLLATE utf8mb4_0900_ai_ci NULL COMMENT '补充user消息；转引导复用源user消息',
    replacement_user_message_id VARCHAR(36) COLLATE utf8mb4_0900_ai_ci NULL COMMENT '编辑共用输入时Java预建的隐藏替代消息',
    issued_by VARCHAR(64) NOT NULL COMMENT 'Java校验后的操作者主体，禁止从正文信任',
    expected_run_revision BIGINT UNSIGNED NULL COMMENT '编辑/移除/转引导的条件版本',
    payload_json JSON NOT NULL COMMENT '带schemaVersion的白名单文本/控制参数；不存凭据',
    status VARCHAR(16) NOT NULL DEFAULT 'accepted' COMMENT 'accepted/processing/delivered/applied/rejected/unknown',
    processing_epoch BIGINT UNSIGNED NULL COMMENT '开始处理时的session租约epoch，用于恢复判定',
    result_json JSON NULL COMMENT '脱敏回执：code、revision、activeRunId、expiresAt等',
    created_at DATETIME(3) NOT NULL,
    updated_at DATETIME(3) NOT NULL,
    PRIMARY KEY (command_id),
    UNIQUE KEY uk_rtc_order (conversation_id, command_seq),
    UNIQUE KEY uk_rtc_steering (target_run_id, steering_message_id),
    KEY idx_rtc_pending (conversation_id, status, command_seq),
    CONSTRAINT fk_rtc_session FOREIGN KEY (conversation_id) REFERENCES t_ai_center_runtime_session (conversation_id),
    CONSTRAINT fk_rtc_target FOREIGN KEY (conversation_id, target_run_id) REFERENCES t_ai_center_runtime_run (conversation_id, run_id),
    CONSTRAINT fk_rtc_source FOREIGN KEY (conversation_id, source_run_id) REFERENCES t_ai_center_runtime_run (conversation_id, run_id),
    CONSTRAINT fk_rtc_steering_message FOREIGN KEY (steering_message_id) REFERENCES t_ai_center_message (id),
    CONSTRAINT fk_rtc_replacement_message FOREIGN KEY (replacement_user_message_id) REFERENCES t_ai_center_message (id),
    CONSTRAINT ck_rtc_type CHECK (command_type IN ('pause_queue', 'resume_queue', 'cancel_run', 'acquire_edit', 'renew_edit', 'release_edit', 'save_edit', 'steer_run', 'promote_to_steer', 'close_session', 'resolve_uncertainty')),
    CONSTRAINT ck_rtc_status CHECK (status IN ('accepted', 'processing', 'delivered', 'applied', 'rejected', 'unknown')),
    CONSTRAINT ck_rtc_target CHECK ((command_type IN ('pause_queue', 'resume_queue', 'close_session') AND target_run_id IS NULL) OR (command_type NOT IN ('pause_queue', 'resume_queue', 'close_session') AND target_run_id IS NOT NULL)),
    CONSTRAINT ck_rtc_steering CHECK ((command_type IN ('steer_run', 'promote_to_steer') AND steering_message_id IS NOT NULL) OR (command_type NOT IN ('steer_run', 'promote_to_steer') AND steering_message_id IS NULL)),
    CONSTRAINT ck_rtc_source CHECK ((command_type = 'promote_to_steer' AND source_run_id IS NOT NULL AND source_run_id <> target_run_id) OR (command_type <> 'promote_to_steer' AND source_run_id IS NULL)),
    CONSTRAINT ck_rtc_replacement CHECK (replacement_user_message_id IS NULL OR command_type = 'save_edit'),
    CONSTRAINT ck_rtc_order CHECK (command_seq > 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_bin COMMENT='持久控制命令与引导回执';

CREATE TABLE t_ai_center_runtime_event (
    conversation_id VARCHAR(36) COLLATE utf8mb4_0900_ai_ci NOT NULL,
    session_sequence BIGINT UNSIGNED NOT NULL COMMENT '会话级投影游标，与Run sequence区分',
    run_id VARCHAR(256) CHARACTER SET ascii COLLATE ascii_bin NULL COMMENT '纯队列事件可为空',
    run_sequence BIGINT UNSIGNED NULL COMMENT '保留现有Run事件顺序和重放语义',
    event_id VARCHAR(256) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT '现有事件信封ID，重试不能重新生成',
    event_type VARCHAR(64) NOT NULL COMMENT '现有Run类型或会话级队列/命令事件',
    payload_json JSON NOT NULL COMMENT '公共脱敏事件；不存原始SDK trace或凭据',
    occurred_at DATETIME(3) NOT NULL,
    PRIMARY KEY (conversation_id, session_sequence),
    UNIQUE KEY uk_rte_run_sequence (run_id, run_sequence),
    UNIQUE KEY uk_rte_event_id (conversation_id, event_id),
    KEY idx_rte_retention (occurred_at),
    CONSTRAINT fk_rte_session FOREIGN KEY (conversation_id) REFERENCES t_ai_center_runtime_session (conversation_id),
    CONSTRAINT fk_rte_run FOREIGN KEY (conversation_id, run_id) REFERENCES t_ai_center_runtime_run (conversation_id, run_id),
    CONSTRAINT ck_rte_sequence CHECK (session_sequence > 0 AND ((run_id IS NULL AND run_sequence IS NULL) OR (run_id IS NOT NULL AND run_sequence IS NOT NULL AND run_sequence > 0)))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_bin COMMENT='状态事务内提交的公共事件，不作为第二份队列';

CREATE TABLE t_ai_center_runtime_artifact (
    artifact_id VARCHAR(256) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    run_id VARCHAR(256) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    status VARCHAR(16) NOT NULL DEFAULT 'pending',
    snapshot_json JSON NOT NULL COMMENT '白名单：名称、大小、摘要、受控相对快照引用；无临时签名URL',
    platform_file_id VARCHAR(256) NULL COMMENT '上传成功后的既有文件服务ID',
    result_json JSON NULL COMMENT '白名单文件卡片元数据；Java幂等投影到writing_attachments',
    processing_epoch BIGINT UNSIGNED NULL COMMENT '上传开始时session租约epoch；不证明外部幂等',
    error_code VARCHAR(64) NULL,
    created_at DATETIME(3) NOT NULL,
    updated_at DATETIME(3) NOT NULL,
    PRIMARY KEY (artifact_id),
    KEY idx_rta_run (run_id, status),
    CONSTRAINT fk_rta_run FOREIGN KEY (run_id) REFERENCES t_ai_center_runtime_run (run_id),
    CONSTRAINT ck_rta_status CHECK (status IN ('pending', 'uploading', 'ready', 'failed', 'unknown')),
    CONSTRAINT ck_rta_ready CHECK (status <> 'ready' OR platform_file_id IS NOT NULL)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_bin COMMENT='成果持久快照与上传结果，不复制输入附件';
